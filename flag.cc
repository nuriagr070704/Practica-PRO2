void Flag::paint(pro2::Window& window) const {
    const Pt top_left = {pos_.x - 6, pos_.y - 15};
    if (!taken_) paint_sprite(window, top_left, flag_sprite_normal_, false);
    else paint_sprite(window, top_left, flag_sprite_win_, false);
}

void Flag::update(pro2::Window& window, Mario& mario) {
    Pt pos_mario = mario.pos();
    if (pos_mario.x >= pos_.x - 10 && pos_mario.x <= pos_.x + 7) {
        if (pos_mario.y >= pos_.y - 20 && pos_mario.y <=  pos_.y + 30) {
            taken_ = true;
        }
    }
}